from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:3000')
    page.get_by_role('button',name='Pacientes',exact=True).click();page.get_by_role('button',name='Novo paciente',exact=True).click()
    page.get_by_label('Nome completo',exact=True).fill('Paciente fictício')
    page.get_by_label('Evolução do paciente',exact=True).fill('Avaliação inicial fictícia')
    page.get_by_label('Nota da condição funcional (0 a 10, opcional)',exact=True).fill('0')
    page.get_by_role('button',name='Salvar',exact=True).click()
    expect(page.locator('#modal')).not_to_be_visible()
    page.get_by_role('button',name='Ver histórico e evolução',exact=True).click()
    expect(page.get_by_text('Avaliação inicial fictícia',exact=True)).to_be_visible()
    expect(page.locator('svg.progress-chart')).to_be_visible()
    page.get_by_role('button',name='Registrar evolução',exact=True).click()
    page.get_by_label('Evolução do paciente',exact=True).fill('Melhora fictícia')
    page.get_by_label('Nota da condição funcional (0 a 10, opcional)',exact=True).fill('8')
    page.get_by_role('button',name='Salvar',exact=True).click();expect(page.locator('#modal')).not_to_be_visible()
    expect(page.locator('svg.progress-chart circle')).to_have_count(2)
    page.screenshot(path='/tmp/camila-patient-progress.png',full_page=True)
    page.get_by_role('button',name='Atendimentos',exact=True).click()
    for modality,amount in [('physiotherapy','100'),('pilates','80')]:
        page.get_by_role('button',name='Novo atendimento',exact=True).click()
        page.locator('#fields select[name=treatment]').select_option(modality)
        page.get_by_label('Valor (R$)',exact=True).fill(amount)
        page.get_by_role('button',name='Salvar',exact=True).click();expect(page.locator('#modal')).not_to_be_visible()
    expect(page.locator('#content .row')).to_have_count(2)
    page.locator('#treatment-filter').select_option('pilates');expect(page.locator('#content .row')).to_have_count(1)
    expect(page.locator('#content .amount')).to_contain_text('80,00')
    page.get_by_role('button',name='Excluir',exact=True).click()
    page.get_by_role('button',name='Fechar',exact=True).click();expect(page.locator('#content .row')).to_have_count(1)
    page.get_by_role('button',name='Excluir',exact=True).click()
    page.get_by_role('button',name='Confirmar exclusão',exact=True).click();expect(page.locator('#content .row')).to_have_count(0)
    page.get_by_role('button',name='Financeiro',exact=True).click();expect(page.locator('#finance-details .card').nth(2).locator('strong')).to_contain_text('0,00')
    page.locator('#treatment-filter').select_option('physiotherapy');expect(page.locator('#finance-details .card').nth(2).locator('strong')).to_contain_text('100,00')
    page.reload();page.get_by_role('button',name='Atendimentos',exact=True).click();expect(page.locator('#content .row')).to_have_count(1)
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    assert not errors,errors
    print('PASS: evolução inicial, nota zero, gráfico, evolução adicional, modalidades, cancelamento e confirmação de exclusão, financeiro e persistência móvel.')
    browser.close()
